#!/bin/bash
# Shared library: port slot management and docker-compose.yml assembly.
# Requires PROJECT_ROOT to be set by the caller before sourcing.
# Usage: source "$(dirname "$0")/lib-ports.sh"

PROJECTS_CONF="${HOME}/.config/docker-projects.conf"

_G='\033[0;32m'; _Y='\033[1;33m'; _R='\033[0;31m'; _C='\033[0;36m'; _N='\033[0m'

# Читает "name" из package.json корня проекта; fallback — имя папки.
# Нормализует: lowercase, [^a-z0-9_-] → '_'
_get_project_name() {
    local root="${1:-$PROJECT_ROOT}"
    local name=""
    if [ -f "$root/package.json" ]; then
        name=$(grep -m1 '"name"' "$root/package.json" \
               | sed 's/.*"name"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/')
    fi
    [ -z "$name" ] && name=$(basename "$root")
    echo "$name" | tr '[:upper:]' '[:lower:]' | sed 's/[^a-z0-9_-]/_/g'
}
_lib_ok()   { echo -e "${_G}[✓]${_N} $1" >&2; }
_lib_info() { echo -e "${_C}[*]${_N} $1" >&2; }
_lib_warn() { echo -e "${_Y}[!]${_N} $1" >&2; }
_lib_fail() { echo -e "${_R}[-]${_N} $1" >&2; }

# ── Вычислить порты для слота N ───────────────────────────────────
# Устанавливает: DB_PORT REDIS_PORT API_PORT API_DEBUG_PORT FRONT_PORT PARSER_PORT
ports_for_slot() {
    local slot=$1
    DB_PORT=$(( 5432 + slot ))
    REDIS_PORT=$(( 6379 + slot ))
    API_PORT=$(( 3000 + slot ))
    API_DEBUG_PORT=$(( 9230 + slot ))
    FRONT_PORT=$(( 4200 + slot ))
    PARSER_PORT=$(( 8000 + slot ))
}

# ── Проверить один порт ───────────────────────────────────────────
_port_busy() {
    ss -tlnp 2>/dev/null | grep -q ":$1 "
}

# ── Все порты выбранных сервисов свободны? (0=да, 1=нет) ─────────
# Аргументы: SLOT SEL (например "0+1+3+4")
ports_free() {
    local slot=$1 sel=$2
    ports_for_slot "$slot"
    [[ $sel == *4* ]] && _port_busy "$DB_PORT"        && return 1
    [[ $sel == *5* ]] && _port_busy "$REDIS_PORT"     && return 1
    [[ $sel == *0* ]] && _port_busy "$API_PORT"       && return 1
    [[ $sel == *0* ]] && _port_busy "$API_DEBUG_PORT" && return 1
    [[ $sel == *1* || $sel == *2* ]] && _port_busy "$FRONT_PORT" && return 1
    [[ $sel == *3* ]] && _port_busy "$PARSER_PORT"    && return 1
    return 0
}

# ── Найти первый свободный слот (печатает номер) ─────────────────
find_free_slot() {
    local sel=$1
    local slot=0
    while [ $slot -le 20 ]; do
        if ports_free "$slot" "$sel"; then
            echo "$slot"
            return 0
        fi
        slot=$(( slot + 1 ))
    done
    _lib_fail "Нет свободных слотов (проверено 0–20)"
    return 1
}

# ── Собрать docker-compose.yml из фрагментов ─────────────────────
build_compose() {
    local sel=$1
    local frags="${PROJECT_ROOT}/docker/fragments"
    local out="${PROJECT_ROOT}/docker-compose.yml"

    {
        echo "# generated by lib-ports.sh — не редактировать вручную"
        echo "# для пересборки: bin/reset-ports.sh"
        echo "services:"
        [[ $sel == *4* ]] && cat "$frags/db.yml"
        [[ $sel == *5* ]] && cat "$frags/redis.yml"
        if [[ $sel == *0* ]]; then
            cat "$frags/backend.yml"
            local deps=()
            [[ $sel == *4* ]] && deps+=("db")
            [[ $sel == *5* ]] && deps+=("redis")
            if [ ${#deps[@]} -gt 0 ]; then
                echo "    depends_on:"
                for dep in "${deps[@]}"; do
                    echo "      ${dep}:"
                    echo "        condition: service_healthy"
                done
            fi
        fi
        [[ $sel == *1* ]] && cat "$frags/frontend-angular.yml"
        [[ $sel == *2* ]] && cat "$frags/frontend-nextjs.yml"
        [[ $sel == *3* ]] && cat "$frags/fastapi.yml"
        local has_vol=0
        [[ $sel == *4* ]] && has_vol=1
        [[ $sel == *5* ]] && has_vol=1
        [[ $sel == *0* ]] && has_vol=1
        [[ $sel == *1* || $sel == *2* ]] && has_vol=1
        if [ $has_vol -eq 1 ]; then
            echo ""
            echo "volumes:"
            [[ $sel == *4* ]] && echo "  db-data:"
            [[ $sel == *5* ]] && echo "  redis-data:"
            [[ $sel == *0* ]] && echo "  api_node_modules:"
            [[ $sel == *1* ]] && echo "  front_node_modules:"
            if [[ $sel == *2* ]]; then
                echo "  front_node_modules:"
                echo "  front_next:"
            fi
        fi
    } > "$out"
}

# ── Обновить внешние URL в sub-env'ах при смене слота ────────────
update_sub_envs() {
    local sel=$1

    if [[ $sel == *0* ]] && [ -f "${PROJECT_ROOT}/backend/.env" ]; then
        sed -i \
            -e "s|^API_URL=.*|API_URL=http://localhost:${API_PORT}|" \
            -e "s|^FRONT_URL=.*|FRONT_URL=http://localhost:${FRONT_PORT}|" \
            -e "s|^CORS_ORIGIN=.*|CORS_ORIGIN=http://localhost:${FRONT_PORT}|" \
            -e "s|^GOOGLE_CALLBACK_URL=.*|GOOGLE_CALLBACK_URL=http://localhost:${API_PORT}/auth/google/callback|" \
            "${PROJECT_ROOT}/backend/.env"
        _lib_info "backend/.env — внешние URL обновлены"
    fi

    if [[ $sel == *1* ]] && [ -f "${PROJECT_ROOT}/frontend/.env" ]; then
        sed -i \
            -e "s|^API_URL=.*|API_URL=http://localhost:${API_PORT}|" \
            "${PROJECT_ROOT}/frontend/.env"
        _lib_info "frontend/.env (Angular) — обновлён"
    fi

    if [[ $sel == *2* ]] && [ -f "${PROJECT_ROOT}/frontend/.env" ]; then
        sed -i \
            -e "s|^NEXT_PUBLIC_API_URL=.*|NEXT_PUBLIC_API_URL=http://localhost:${API_PORT}|" \
            "${PROJECT_ROOT}/frontend/.env"
        _lib_info "frontend/.env (Next.js) — обновлён"
    fi
}

# ── Применить слот: .env + docker-compose.yml + sub-envs + реестр ─
apply_slot() {
    local slot=$1 sel=$2
    local name
    name=$(_get_project_name "${PROJECT_ROOT}")

    ports_for_slot "$slot"

    # Обновить порты в .env
    local env="${PROJECT_ROOT}/.env"
    if [ -f "$env" ]; then
        sed -i \
            -e "s|^DB_PORT=.*|DB_PORT=${DB_PORT}|" \
            -e "s|^REDIS_PORT=.*|REDIS_PORT=${REDIS_PORT}|" \
            -e "s|^API_PORT=.*|API_PORT=${API_PORT}|" \
            -e "s|^API_DEBUG_PORT=.*|API_DEBUG_PORT=${API_DEBUG_PORT}|" \
            -e "s|^FRONT_PORT=.*|FRONT_PORT=${FRONT_PORT}|" \
            -e "s|^PARSER_PORT=.*|PARSER_PORT=${PARSER_PORT}|" \
            "$env"
    fi

    build_compose "$sel"
    update_sub_envs "$sel"

    # Обновить реестр
    mkdir -p "${HOME}/.config"
    touch "$PROJECTS_CONF"
    if grep -q "^${name}:" "$PROJECTS_CONF" 2>/dev/null; then
        sed -i "s|^${name}:.*|${name}:${slot}|" "$PROJECTS_CONF"
    else
        echo "${name}:${slot}" >> "$PROJECTS_CONF"
    fi

    _lib_ok "Слот ${slot} → DB=${DB_PORT} Redis=${REDIS_PORT} API=${API_PORT} Front=${FRONT_PORT}"
}

# ── Авто-проверка: сменить слот если текущие порты заняты ────────
auto_fix_ports() {
    local env="${PROJECT_ROOT}/.env"
    [ ! -f "$env" ] && return 0

    # Если наши контейнеры уже запущены — порты наши, не трогаем
    if docker compose --project-directory "${PROJECT_ROOT}" ps --status running 2>/dev/null | grep -q .; then
        return 0
    fi

    local sel
    sel=$(grep '^COMPOSE_SERVICES=' "$env" | cut -d= -f2)
    [ -z "$sel" ] && return 0

    # Определить текущий слот по DB_PORT
    local cur_db
    cur_db=$(grep '^DB_PORT=' "$env" | cut -d= -f2)
    local cur_slot=$(( ${cur_db:-5432} - 5432 ))

    # Найти наименьший свободный слот (всегда пробует 0 первым)
    local best_slot
    best_slot=$(find_free_slot "$sel") || return 1

    # Уже на оптимальном слоте — ничего не делаем
    if [ "$best_slot" -eq "$cur_slot" ]; then
        return 0
    fi

    _lib_warn "Слот ${cur_slot} → слот ${best_slot}"
    apply_slot "$best_slot" "$sel"
}
